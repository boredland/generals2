#!/usr/bin/env python3
"""Write crates/g2-maps/src/garrisonable.txt: every Generals / Zero Hour structure template that
infantry can garrison (an active `GarrisonContain` module), with its footprint as a circle radius
in SAGE units. Source: GeneralsGamePatch2's INI (GPL-3.0, vendor/superhackers/GeneralsGamePatch2),
Zero Hour taking precedence over Generals. A BOX footprint becomes its inscribed circle (half its
short side), so a building never blocks ground the original game left open; a CYLINDER keeps its
radius. `ObjectReskin` copies inherit their base's modules and geometry unless they override
them. Deterministic: run it again after a submodule bump.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "vendor/superhackers/GeneralsGamePatch2"
OUT = ROOT / "crates/g2-maps/src/garrisonable.txt"


def strip_comments(text):
    return "\n".join(line.split(";", 1)[0].split("//", 1)[0] for line in text.splitlines())


def field(block, key):
    m = re.search(r"^\s*" + key + r"\s*=\s*([^\s]+)", block, re.M)
    return m.group(1) if m else None


def blocks(game):
    """(kind, name, base, body) per top-level Object / ObjectReskin in the game's INI."""
    for f in sorted((SRC / game / "Data/INI/Object").rglob("*.ini")):
        text = strip_comments(f.read_text(errors="replace"))
        for chunk in re.split(r"\n(?=(?:Object|ObjectReskin)\s)", "\n" + text):
            m = re.match(r"\s*(ObjectReskin|Object)\s+(\S+)(?:\s+(\S+))?", chunk)
            if m:
                yield m.group(1), m.group(2), m.group(3), chunk


def radius(body):
    geo = field(body, "Geometry")
    major = field(body, "GeometryMajorRadius")
    minor = field(body, "GeometryMinorRadius")
    if geo is None or major is None:
        return None
    major = float(major)
    if geo.upper() == "BOX" and minor:
        return min(major, float(minor))
    return major


def garrisonable(body):
    line = re.search(r"^\s*KindOf\s*=(.*)$", body, re.M)
    kinds = line.group(1).split() if line else []
    return "STRUCTURE" in kinds and re.search(r"=\s*GarrisonContain\b", body) is not None


def main():
    templates = {}
    for game in ["Generals", "GeneralsZH"]:
        objects = {}
        reskins = []
        for kind, name, base, body in blocks(game):
            if kind == "Object":
                objects[name] = body
            else:
                reskins.append((name, base, body))
        for name, body in objects.items():
            r = radius(body)
            if garrisonable(body) and r:
                templates[name] = r
        for name, base, body in reskins:
            if base in objects and garrisonable(objects[base]):
                r = radius(body) or radius(objects[base])
                if r:
                    templates[name] = r
    lines = [
        "# Garrisonable Generals / Zero Hour structures: template, footprint radius in SAGE units.",
        "# Generated by scripts/garrisonable.py from GeneralsGamePatch2's INI (GPL-3.0).",
    ]
    lines += [f"{name} {templates[name]:.1f}" for name in sorted(templates)]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(templates)} templates -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
